#!/usr/bin/env tsx
/**
 * Re-anchor the committed DS fixture dates into the current academic year,
 * in place, without re-running the LLM parser.
 *
 * The original fixtures were generated with a single linear date offset, which
 * couldn't rescue courses whose years were mis-extracted by a decade (ds-s1 had
 * whole courses in 2035/2037, ds-s2 one in 2028). This applies the same
 * academic-year anchoring the parser now uses (src/lib/academicCalendar.ts), so
 * every deadline lands in the current year — a November deadline becomes this
 * November, etc.
 *
 * Usage: npx tsx scripts/renormalize-fixture-dates.ts
 */

import * as fs from "fs";
import * as path from "path";
import type { Course } from "../src/lib/types";
import { academicFallYear, anchorToAcademicYear } from "../src/lib/academicCalendar";
import { dsS1 } from "../src/data/fixtures/ds-s1";
import { dsS2 } from "../src/data/fixtures/ds-s2";

const OUT_DIR = path.resolve(__dirname, "..", "src", "data", "fixtures");
const ref = new Date();
const FALL = academicFallYear(ref);

// Correct the stale/mis-parsed year in a term label while preserving its
// semester word (e.g. "Fall 2024" → "Fall 2026", "2013/2014" → "2026-2027").
function normalizeTerm(term: string): string {
  const t = (term || "").toLowerCase();
  if (t.includes("fall") && t.includes("winter"))
    return `Fall/Winter ${FALL}-${String(FALL + 1).slice(2)}`;
  if (t.includes("fall")) return `Fall ${FALL}`;
  if (t.includes("winter")) return `Winter ${FALL + 1}`;
  if (t.includes("summer")) return `Summer ${FALL + 1}`;
  return `${FALL}-${FALL + 1}`;
}

// Anchor every event's date (and any recurring endDate) into the current
// academic year, preserving month/day, then re-sort. We anchor-only here (no
// window filter) so curated demo courses never lose events.
function remap(courses: Course[]): Course[] {
  return courses.map((course) => {
    const events = course.events
      .map((e) => {
        const next = { ...e, date: anchorToAcademicYear(e.date, ref) };
        if (next.recurringPattern?.endDate) {
          next.recurringPattern = {
            ...next.recurringPattern,
            endDate: anchorToAcademicYear(next.recurringPattern.endDate, ref),
          };
        }
        return next;
      })
      .sort((a, b) => a.date.localeCompare(b.date));
    return { ...course, term: normalizeTerm(course.term), events };
  });
}

function write(varName: string, file: string, courses: Course[]) {
  const content = `// AUTO-GENERATED by scripts/generate-fixtures.ts — do not edit by hand
import type { Course } from "@/lib/types";

export const ${varName}: Course[] = ${JSON.stringify(courses, null, 2)};
`;
  fs.writeFileSync(path.join(OUT_DIR, file), content);
  const dates = courses.flatMap((c) => c.events.map((e) => e.date)).sort();
  console.log(`  → ${file}: ${dates.length} events, ${dates[0]} … ${dates[dates.length - 1]}`);
}

write("dsS1", "ds-s1.ts", remap(dsS1));
write("dsS2", "ds-s2.ts", remap(dsS2));
console.log("Done — DS fixture dates re-anchored to the current academic year.");
