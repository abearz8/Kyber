#!/usr/bin/env tsx
/**
 * Parse all 16 syllabi and write TypeScript fixture files.
 *
 * Usage (reads ANTHROPIC_API_KEY from .env.local automatically):
 *   npx tsx scripts/generate-fixtures.ts
 *
 * Writes:
 *   src/data/fixtures/hba1-s1.ts   (HBA1 First Semester, 5 courses)
 *   src/data/fixtures/hba1-s2.ts   (HBA1 Second Semester, 4 courses)
 *   src/data/fixtures/ds-s1.ts     (Data Science First Semester, 4 courses)
 *   src/data/fixtures/ds-s2.ts     (Data Science Second Semester, 3 courses)
 */

import * as fs from "fs";
import * as path from "path";
import { loadEnvConfig } from "@next/env";
import { parseBytes } from "../src/lib/parser/index";
import { PALETTE } from "../src/lib/parser/schema";
import type { Course } from "../src/lib/types";

const ROOT = path.resolve(__dirname, "..");

// Load .env.local (and friends) the same way `next dev` does, so the script
// picks up ANTHROPIC_API_KEY without needing to export it manually.
loadEnvConfig(ROOT);
const SOURCES = path.join(ROOT, "sources", "Sylabus examples");
const OUT_DIR = path.join(ROOT, "src", "data", "fixtures");

// Map of output fixture → list of PDF paths relative to SOURCES
const FIXTURES: Record<string, string[]> = {
  "hba1-s1": [
    "HBA1/First semester/HBA Course Outline 2025-2026 BUS3303 Sec 3&4.pdf",
    "HBA1/First semester/3302 Outline 2025-2026 Updated 8272025.pdf",
    "HBA1/First semester/HBA Course Outline AFF 2025-2026.pdf",
    "HBA1/First semester/3316 Course Outline 2025.pdf",
    "HBA1/First semester/Course Outline LPO 2025.pdf",
  ],
  "hba1-s2": [
    "HBA1/Second Semester/3304 Operations Course Outline.pdf",
    "HBA1/Second Semester/BUS 3301 HBA Course Outline.pdf",
    "HBA1/Second Semester/HBA Course Outline 2025-2026 LIT.pdf",
    "HBA1/Second Semester/3300 - HBA Course Outline 2025-2026.pdf",
  ],
  "ds-s1": [
    "Data Science/First semester/MATH1600A.pdf",
    "Data Science/First semester/2022-CS1026-a.pdf",
    "Data Science/First semester/Film1020E-002.pdf",
    "Data Science/First semester/CALC1000A.pdf",
  ],
  "ds-s2": [
    "Data Science/Second Semester/CALC1501B-2023.pdf",
    "Data Science/Second Semester/CS_1027B_FW24.pdf",
    "Data Science/Second Semester/DS1000---S2023-Course-Outline.pdf",
  ],
};

// Note: event dates no longer need a separate offset pass here. The parser's
// normalize() anchors every date into the current academic year (see
// src/lib/academicCalendar.ts), so parsed courses are already current.

function fixtureFileContent(varName: string, courses: Course[]): string {
  return `// AUTO-GENERATED by scripts/generate-fixtures.ts — do not edit by hand
import type { Course } from "@/lib/types";

export const ${varName}: Course[] = ${JSON.stringify(courses, null, 2)};
`;
}

async function main() {
  if (!process.env.ANTHROPIC_API_KEY) {
    console.error("ERROR: ANTHROPIC_API_KEY environment variable is not set.");
    process.exit(1);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const started = Date.now();
  console.log("Parsing all syllabi concurrently…\n");

  // Parse every PDF across every fixture in parallel. Each fixture's courses
  // keep input order (Promise.all preserves it) so palette colors stay stable.
  const tasks = Object.entries(FIXTURES).map(async ([fixtureName, pdfPaths]) => {
    const parsed = await Promise.all(
      pdfPaths.map(async (rel, i): Promise<Course | null> => {
        const absPath = path.join(SOURCES, rel);
        const filename = path.basename(absPath);

        if (!fs.existsSync(absPath)) {
          console.warn(`  WARN: File not found: ${absPath}`);
          return null;
        }

        try {
          const data = fs.readFileSync(absPath);
          const color = PALETTE[i % PALETTE.length];
          const course = await parseBytes(data, filename, color);
          console.log(`  ✓ ${course.code} — ${course.title} (${course.events.length} events)`);
          return course;
        } catch (err) {
          console.error(`  ✗ ${filename} failed: ${err instanceof Error ? err.message : err}`);
          return null;
        }
      })
    );

    const courses = parsed.filter((c): c is Course => c !== null);

    const varName = fixtureName.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
    const outPath = path.join(OUT_DIR, `${fixtureName}.ts`);
    fs.writeFileSync(outPath, fixtureFileContent(varName, courses));
    console.log(`  → Wrote ${fixtureName}.ts (${courses.length}/${pdfPaths.length} courses)`);
  });

  await Promise.all(tasks);

  const secs = ((Date.now() - started) / 1000).toFixed(1);
  console.log(`\nDone! All fixtures generated in ${secs}s.`);
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
